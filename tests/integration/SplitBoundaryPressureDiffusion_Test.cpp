/** Analytic one-dimensional temperature profile in homogeneous material.
 
    @param T0 temperature of medium before boundary temperature was changed (oC)
    @param kappa thermal diffusivity (m2/s)
    @param x distance from interface (m)
    @param t time (s)
*/
double temperatureDiffusion1D( double T0, double kappa, double x, double t )
 {
    return T0 * erf( x / (2. * sqrt( kappa * t ) ) );
 }



/** Derivative * thermal conductivity product at x0
*/
double heatFlow1DAtX0( double T0, double kappa, double t, double K )
 {
    // derivative pf previous expression
    constexpr double pi = 3.14159265358979323846;
    const double     sqrtPi{ sqrt(pi) }, x{0.};
    const double     x2{ x * x };
    double dTdx  = T0 * exp( -x2 ) / (4. * kappa * t);
    dTdx /= sqrtPi * sqrt( kappa * t );

    // heat flux
    return dTdx * K;
 }



