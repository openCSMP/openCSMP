/**
   Checks whethe the assignment of element neighbors from SKUA is identical with that done by CSMP; the side boundary flags are not considered.
   
      TODO: also check neighbor connectivity of Face and InterFace objects
*/
bool SKUA_FiniteElementMeshInterface_Test::TestElementNeighborConnectivity( Model<3U>& model )
 {
    const csmp::Index eidx = model.Database().StorageKey("element number");
    const csmp::Index nidx = model.Database().StorageKey("node number");
    Region<3U>& domain(model.Region("Model"));
    // recording connectivity from SKUA in an element neighbor vector
    vector<vector<Element<3U>*> > pfverts;
    pfverts.reserve( domain.Cells() );
    for ( auto it=domain.CellsBegin(); it!=domain.CellsEnd(); ++it ) {
         vector<Element<3U>*> nbors( (*it)->Neighbors(), nullptr );
         for ( auto i{0}; i<(*it)->Neighbors(); ++i )
           if ( (*it)->Neighbor(i) != nullptr )
             nbors[i] = (*it)->Neighbor(i);
         pfverts.push_back( nbors );
      }
      
   if ( verbose_ ) PrintOriginalNeighborIDs( model );
      
    // recreating the connectivity in CSMP
    model.Mesh().UpdateConnectivity();
    if ( verbose_ ) PrintOriginalNeighborIDs( model );
    
    // comparing SKUA with CSMP connectivity
    size_t failed_comparisons(0U);
    vector<vector<Element<3U>*> >::const_iterator pfit(pfverts.begin());
    for ( auto it=domain.CellsBegin(); it!=domain.CellsEnd(); ++it, ++pfit ) {
         for ( auto i{0}; i<(*it)->Neighbors(); ++i )
           if ( (*it)->Neighbor(i) != (*pfit)[i] ) {
                if ( verbose_ ) {
                     //(*it)->Out();
                     cerr <<"\nelement neighbor "<< (*it)->Read(eidx) <<":"<< i <<": ";
                     cerr << (*it)->Neighbor(i)->Idx() <<" vs. "<< (*pfit)[i]->Read(eidx) <<" ";
                  }
                failed_comparisons++;
             }
      }
    if ( verbose_ && failed_comparisons > 0 ) cerr << endl;
      
    if ( failed_comparisons > 0U ) return false;  
    return true;
    
 } // end TestElementNeighborConnectivity
 
 
 
 
/** tests whether the number of nodes in InterFace cells is consistent with their parent tetrahedral Element cells
 
        Uses the VSet 'pfvert' record to recover the necessary information for each InterFace: this record is expect to contain:
        interface neighbors(entries 0..2), inner-parent elmt(3), outer-parent elmt(4), inner-face idx(5), outer-face idx(6), intervening-elmt idx(7) or INTERNAL (see OutputMeshToVSet)
 */
void SKUA_FiniteElementMeshInterface_Test::Test_NodeNumberingConsistencyBetweenTetrahedraAndInterFaces( const VData& vdata )
 {
    assert( vdata.HybridElementTypeMesh() );
    assert( vdata.IsoparametricElementMesh() );
    assert( vdata.Interfaces() > 0U );
    
     // looping over the InterFace records in VSet
     for ( size_t i{ vdata.Elements() + vdata.Faces() }; i<vdata.TotalNumberOfCells(); i++ )
       {
          assert( vdata.ElementType(i) == ISOPARAMETRIC_LINEAR_TRIANGLE );
          assert( vdata.PfvertsSize(i) == 8U );
          
          // checking inside element first
          // -----------------------------
          // - the nodes of the INSIDE parent face touching the interface must be exactly the same
          //   (for the linear tet, these are: face 0: 1 2 3, face 1: 0 3 2, 2: 0 1 3, and face 3: 0 2 1)
          const size_t inner_elmt     = vdata.Pfvert(i,3);
          const size_t inner_face_idx = vdata.Pfvert(i,5);
          const size_t node0(vdata.Plist(i,0)), node1(vdata.Plist(i,1)), node2(vdata.Plist(i,2));
          switch( inner_face_idx ) {
              case 0:
                  // first 3 nodes of interface must match those of face 1 of the tetrahedron
                  _test( node0 == vdata.Plist(inner_elmt,1) );
                  _test( node1 == vdata.Plist(inner_elmt,2) );
                  _test( node2 == vdata.Plist(inner_elmt,3) );
                break;
              case 1:
                  _test( node0 == vdata.Plist(inner_elmt,0) );
                  _test( node1 == vdata.Plist(inner_elmt,3) );
                  _test( node2 == vdata.Plist(inner_elmt,2) );
                break;
              case 2:
                  _test( node0 == vdata.Plist(inner_elmt,0) );
                  _test( node1 == vdata.Plist(inner_elmt,1) );
                  _test( node2 == vdata.Plist(inner_elmt,3) );
                break;
              case 3:
                  _test( node0 == vdata.Plist(inner_elmt,0) );
                  _test( node1 == vdata.Plist(inner_elmt,2) );
                  _test( node2 == vdata.Plist(inner_elmt,1) );
            }
          // checking outside element
          // ------------------------
          // - the nodes of the INSIDE parent face touching the interface must be exactly the same
          //   (for the linear tet, these are: face 0: 1 2 3, face 1: 0 3 2, 2: 0 1 3, and face 3: 0 2 1)
          const size_t outer_elmt     = vdata.Pfvert(i,4);
          const size_t outer_face_idx = vdata.Pfvert(i,6);
          const size_t node3(vdata.Plist(i,3)), node4(vdata.Plist(i,4)), node5(vdata.Plist(i,5));
          switch( outer_face_idx ) {
              case 0:
                  // for the outside, these nodes must be listed in reverse order
                  _test( node5 == vdata.Plist(outer_elmt,1) );
                  _test( node4 == vdata.Plist(outer_elmt,2) );
                  _test( node3 == vdata.Plist(outer_elmt,3) );
                break;
              case 1:
                  _test( node5 == vdata.Plist(outer_elmt,0) );
                  _test( node4 == vdata.Plist(outer_elmt,3) );
                  _test( node3 == vdata.Plist(outer_elmt,2) );
                break;
              case 2:
                  _test( node5 == vdata.Plist(outer_elmt,0) );
                  _test( node4 == vdata.Plist(outer_elmt,1) );
                  _test( node3 == vdata.Plist(outer_elmt,3) );
                break;
              case 3:
                  _test( node5 == vdata.Plist(outer_elmt,0) );
                  _test( node4 == vdata.Plist(outer_elmt,2) );
                  _test( node3 == vdata.Plist(outer_elmt,1) );
            }
       }
       
 } // end Test_NodeNumberingConsistencyBetweenTetrahedraAndInterFaces
  
 
 
 
 
 
bool SKUA_FiniteElementMeshInterface_Test::TestNodePropertyAssignment( const Model<3>& model )
 {
    // if the element number is known so that the material IDs can be assigned correctly
    if ( model.Database().IsDefined("node number") ) {
         const csmp::Index nn_key = model.Database().StorageKey("node number");
         const csmp::Index nu_key = model.Database().StorageKey("number");
         // creating a mapping between current elements in region 'Model' and the VSet from the element number
         const Region<3U>& domain = model.Region("Model");
         vector<const Node<3U>*> ordered_nodes(domain.Nodes());

         for ( auto nit=domain.NodesBegin(); nit!=domain.NodesEnd(); ++nit ) {
              if ( fabs((*nit)->Read(nn_key) - (*nit)->Read(nu_key)) > numeric_limits<double>::epsilon() ) { 
                   cerr <<"\n\tnode number vs. number: "<< (*nit)->Read(nn_key) <<" vs. "<< (*nit)->Read(nu_key);
                   _equal( (*nit)->Read(nn_key), (*nit)->Read(nu_key), numeric_limits<double>::epsilon() );
                }
              ordered_nodes[ static_cast<uint32_t>((*nit)->Read(nn_key)) ] = (*nit);
           }
           
         bool problem_found(false);  
         for ( auto i{0}; i<ordered_nodes.size(); ++i ) {
              if ( ordered_nodes[i] == nullptr ) {
                  cerr <<"\nordered nodes map contains nullptr for node "<< i; 
                  problem_found = true;
                }
              else if ( i != static_cast<uint32_t>(ordered_nodes[i]->Read(nu_key)) ) {
                  cerr <<"\nmismatch: node "<< i <<": vs 'number' "<< ordered_nodes[i]->Read(nu_key);
                  problem_found = true;
                }
            }
         if ( problem_found == true ) return false;  
      }       
    return true;

 } // TestNodePropertyAssignment



/**
    This method assumes that the original element numbering was stored in the variable "element number"
*/
void SKUA_FiniteElementMeshInterface_Test::PrintOriginalNeighborIDs( const Model<3U>& model ) const
 {
    // if the element number is known so that the material IDs can be assigned correctly
    if ( model.Database().IsDefined("element number") ) {
         const csmp::Index eid_key = model.Database().StorageKey("element number");
         // creating a mapping between current elements in region 'Model' and the VSet from the element number
         const Region<3U>& domain = model.Region("Model");
         vector<const Element<3U>*> ordered_elmts(domain.Cells());
         for ( auto it=domain.CellsBegin(); it!=domain.CellsEnd(); ++it )
           ordered_elmts[ static_cast<uint32_t>((*it)->Read(eid_key)) ] = (*it);
           
         // reading the VSet material record
         for ( auto it=ordered_elmts.begin(); it!=ordered_elmts.end(); ++it ) {
              cerr <<"\nelmt "<< (*it)->Read( eid_key ) <<": ";
              // printing the neighbors of this element
              for ( auto i{0}; i<(*it)->Neighbors(); ++i )
                if ( (*it)->Neighbor(i) != nullptr )
                  cerr << (*it)->Neighbor(i)->Read( eid_key ) <<" ";
                else 
                  cerr << parseBoundary( (*it)->AtBoundary(i) ) <<" ";
           }
         cerr << endl;
      }
    
  } // end PrintOriginalNeighborIDs



