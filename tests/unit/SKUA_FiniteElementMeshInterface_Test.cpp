void SKUA_FiniteElementMeshInterface_Test::run()
 {
    const string model_name{"skua_cross_bedded_xsmall"};
    // const string model_name{"SKUA_box_shaped_with_split_boundary"};

    // Read VSet binary file generated by SKUA
    VSet<3U> vset;
    double   time = 0.;
    vset.InputFrom( model_name.c_str(), time );
    
    // connectivity checks before VSet is turned into csmp::Model
    Test_NodeNumberingConsistencyBetweenTetrahedraAndInterFaces( vset );
    
    // adding node and element numbering to it
    {
      PropertyData elmt_numbers( ELEMENT, SCALAR, 3U );
      PropertyData node_numbers( NODE, SCALAR, 3U );
      elmt_numbers.Reserve( vset.Elements() );
      node_numbers.Reserve( vset.Vertices() );
      for ( size_t i{0U}; i<vset.Elements(); i++ ) pushBack( elmt_numbers, makeScalar(ANY,i) );
      for ( size_t i{0U}; i<vset.Vertices(); i++ ) pushBack( node_numbers, makeScalar(ANY,i) );
      vset.AddData( "element number", elmt_numbers );
      vset.AddData( "node number", node_numbers );
    }

    // Read ModelTopology file generated by SKUA
    ModelTopology model_topology(true);
    model_topology.InputFromTextFile( model_name.c_str() );
    
    // Build Model using variables file generated by SKUA
    // TODO: variable file needs to contain the variables 'node number' , 'node variable', 'element number' and 'element variable'
    const string variables_file = model_name + "-variables.txt";
    Model<3U>  model( model_topology, vset, variables_file.c_str(), false );

    // Checks...
    if ( verbose_ ) {
         printModelDimensions( model, true );
         model.BoundariesOut();
         model.SplitBoundariesOut();
      }
    
    // =======================================================================
    //      TESTING STARTS HERE
    // =======================================================================
    // 1. basic testing
    /// consecutive numbering of nodes and elements
    /// mesh consistency (Jacobians, element volume range, non-manifold vertices, triangle boxes
    /// pfverts, disambiguated neighbors of lower-dimensional elements
    /// consistent facing directions of surface elements
    /// consecutive numbering of series of line elements
    /// material IDs
    /// test assignment of box boundary flags (sides, edges, corners)
    /// property assignment
    /// use of regions file (is this still needed?)
    // 2. advanced testing
    /// generation of boundaries
    /// generation of split boundaries
  
    // basics
    TestElementNeighborConnectivity( model );
    
    // Check consecutive numbering (if the node numbers from within the VSet have been preserved)
    set<size_t> node_numbers;
    for ( auto nit=model.Mesh().NodesBegin(); nit!=model.Mesh().NodesEnd(); nit++ )
      node_numbers.insert( (*nit).Idx() );
    const bool check_whether_max_value_is_size_minus1{true};
    _test( ConsecutiveSequenceChecker::IsRangeOfUnsignedIntConsecutive( node_numbers, check_whether_max_value_is_size_minus1 ) );
  
    // Testing split boundary functionality
    Test_NodesAndTheirManifolds( model );
    Test_InterfaceNodes( model );
    
    // Testing box-boundary flags under the assumption that neighbor connectivity is correct and the Boundaries were created correctly
    // assuming that the model is box-shaped
    if ( isStrictlyBoxShaped( model ) ) {
        _test( Test_Boundary_BoxBoundary_FlagConsistency( model, "LEFT" ) );
        _test( Test_Boundary_BoxBoundary_FlagConsistency( model, "RIGHT" ) );
        _test( Test_Boundary_BoxBoundary_FlagConsistency( model, "BOTTOM" ) );
        _test( Test_Boundary_BoxBoundary_FlagConsistency( model, "TOP" ) );
        _test( Test_Boundary_BoxBoundary_FlagConsistency( model, "BACK" ) );
        _test( Test_Boundary_BoxBoundary_FlagConsistency( model, "FRONT" ) );
      }
    
    // painting the node manifolds
    if ( verbose_ &&
         model_name == "SKUA_cross_bedded_xsmall" ) {
        VTK_Interface<3U>  vtk_output;
        const csmp::Index  var_key = model.Database().StorageKey("node variable");
        csmp::Region<3U>&  model_domain = model.Region("Model");
        for ( auto nit=model_domain.NodesBegin(); nit!=model_domain.NodesEnd(); ++nit ) {
              if ( (*nit)->IsManifold() )
                // there should be as many branches as materials come together
                (*nit)->Store( var_key, makeScalar(PLAIN,(*nit)->Manifold()->Branches()));
              else
                (*nit)->Store( var_key, makeScalar(PLAIN,0.));
          }
         _test( printRangeOfVariable( model, "node variable" ) > 1U );

          vtk_output.OutputDataToVTK( model, "node-manifolds", "node variable", 0 );

        // checking model boundary flagging
        boxFlagsToVariable( model, "node variable", "element variable" );
    
    //    vtk_output.OutputDataToVTK( model, "porosity", "porosity", 1 );
        vtk_output.OutputDataToVTK( model, "node-flag", "node variable", 1 );
        vtk_output.OutputDataToVTK( model, "element-flag", "element variable", 1 );
        vtk_output.OutputDataToVTK( model, "porosity", "porosity", 1 );

        // creating 'permeability' variable if it does not already exist
        if ( !model.Database().IsDefined("permeability") ) {
             model.CreateProperty( "permeability", "m2", SCALAR, ELEMENT );
          }
        OutputRegionsToVTK( model, "permeability" );
      }
    
 } // end run



// Testing box-boundary flags under the assumption that neighbor connectivity is correct and the Boundaries were created correctly
bool SKUA_FiniteElementMeshInterface_Test::Test_Boundary_BoxBoundary_FlagConsistency( const Model<3U>& model, const string& boundary_name )
 {
    if ( model.ContainsBoundary(boundary_name) ) {
         const Boundary<3U>& boundary = model.Boundary(boundary_name);
         BOX_BOUNDARY        bflag    = parseBoundary( boundary_name );
         // interior nodes
         for ( auto nit=boundary.NodesBegin(); nit!=boundary.PerimeterNodesBegin(); nit++ )
           _test( bflag == (*nit)->AtBoundary() );
         // perimeter nodes
         for ( auto nit=boundary.PerimeterNodesBegin(); nit!=boundary.NodesEnd(); nit++ )
           _test( belongsToSide( bflag, (*nit)->AtBoundary() ) );
           
         // the test was done
         return true;
      }
    return false; // no testing performed
}



  /// Manifolds: 1) are they present at all split boundaries, 2) do they have the right number of entries
void SKUA_FiniteElementMeshInterface_Test::Test_NodesAndTheirManifolds( const Model<3U>& model )
 {
    // 1. are internal or box boundary nodes in SplitBoundaries manifolds
    // ------------------------------------------------------------------
    // 1a. internal split boundary nodes must be manifolds
    bool all_interior_nodes_are_manifolds{true};
    for ( auto split=model.SplitBoundariesBegin(); split!=model.SplitBoundariesEnd(); split++ )
      for ( auto nit=(*split).second.NodesBegin(); nit!=(*split).second.PerimeterNodesBegin(); nit++ )
        if ( (*nit)->IsManifold() == false ) {
             all_interior_nodes_are_manifolds = false;
             break;
          }
    _test( all_interior_nodes_are_manifolds == true );

    // 1b. perimeter nodes on Box boundaries must also be manifolds
    bool box_boundary_nodes_are_manifolds{true};
    for ( auto split=model.SplitBoundariesBegin(); split!=model.SplitBoundariesEnd(); split++ )
      for ( auto nit=(*split).second.PerimeterNodesBegin(); nit!=(*split).second.NodesEnd(); nit++ )
        if ( ((*nit)->AtBoundary() != NOT && (*nit)->AtBoundary() != INTERNAL) &&
               (*nit)->IsManifold() == false ) {
             box_boundary_nodes_are_manifolds = false;
             break;
          }
    _test( box_boundary_nodes_are_manifolds == true );


    // 2. are all manifold nodes collocated? - initially they must be
    // --------------------------------------------------------------
    size_t not_collocated_nodes{0U};
    for ( auto nit=model.Mesh().NodeManifoldsBegin(); nit!=model.Mesh().NodeManifoldsEnd(); nit++ )
        if ( (*nit).AreNodesCollocated() == false ) {
             if ( verbose_ ) {
                  cout <<"\n"<<"detected manifold the nodes in which are not collocated:";
                  (*nit).Out();
               }
             not_collocated_nodes++;
          }
    _test( not_collocated_nodes == 0U );
     
 } // end Test_NodesAndTheirManifolds
 
 
 
  
/**
     Tests whether INSIDE Interface nodes match those on the outside.
     
     @attention will work also for perimeter InterFace objects where INSIDE and OUTSIDE nodes may be the same.
 */
void SKUA_FiniteElementMeshInterface_Test::Test_InterfaceNodes( const Model<3U>& model )
 {
    for ( auto it=model.Mesh().InterFacesBegin(); it!=model.Mesh().InterFacesEnd(); it++ )
      {
          const auto n_nodes{ (*it).FE()->Nodes() };
          for ( auto i{0U}; i<n_nodes; i++ ) {
              const Point<3U> pt_inside  = (*it).N(i,INSIDE)->Coordinate();
              // the outside nodes must be numbered counter-clockwise and
              // the convention adopted in CSMP is that the last outside node matches the first inside node
              const Point<3U> pt_outside = (*it).N(n_nodes-i-1U,OUTSIDE)->Coordinate();
              // are the nodes co-located? - this uses essentiallyEqual method from compareFloats.h
              _test( pt_inside == pt_outside );
              if ( verbose_ && pt_inside != pt_outside ) {
                   cout <<"\nSKUA_FiniteElementMeshInterface_Test::Test_InterfaceNodes: Interface "<< it->Idx();
                   cout <<": outside nodes do not match inside nodes."<< endl;
                }
            }
      }
      
 } // end Test_InterfaceNodes










